package dev.belikhun.luna.deathswap.world;

import dev.belikhun.luna.core.api.logging.LunaLogger;
import org.bukkit.Bukkit;
import org.bukkit.World;
import org.bukkit.plugin.Plugin;

import java.util.concurrent.CompletableFuture;
import java.util.concurrent.atomic.AtomicInteger;
import java.util.function.DoubleConsumer;

/**
 * Generates the terrain around a spawn point before anyone is sent there, so
 * players land in a finished area instead of watching chunks pop in. Uses
 * Chunky when it is installed (its own throttled generator, real progress);
 * otherwise loads the chunks itself, a few at a time.
 */
public final class SpawnPregen {
	/** radius in blocks around each spawn; timeout per spawn point. */
	public record Options(int radius, int timeoutSeconds) {
	}

	private static final int FALLBACK_IN_FLIGHT = 8;

	private final Plugin plugin;
	private final LunaLogger logger;
	private Options options;
	private ChunkyBridge chunky;
	private boolean chunkyChecked;

	public SpawnPregen(Plugin plugin, LunaLogger logger, Options options) {
		this.plugin = plugin;
		this.logger = logger;
		this.options = options;
	}

	public void setOptions(Options options) {
		this.options = options;
	}

	public Options options() {
		return options;
	}

	public boolean usesChunky() {
		return chunky() != null;
	}

	private ChunkyBridge chunky() {
		if (!chunkyChecked) {
			chunkyChecked = true;
			if (Bukkit.getPluginManager().isPluginEnabled("Chunky")) {
				try {
					chunky = ChunkyBridge.create();
				} catch (ReflectiveOperationException | LinkageError | RuntimeException exception) {
					logger.warn("Chunky is installed but its API could not be used: " + exception.getMessage());
				}
			}
			logger.info(chunky != null
				? "Spawn areas are pre-generated with Chunky (radius " + options.radius() + ")."
				: "Chunky not found; spawn areas are pre-generated by loading chunks directly (radius " + options.radius() + ").");
		}
		return chunky;
	}

	/**
	 * Generate the area around x,z. {@code progress} receives 0..1 from any
	 * thread. The future completes (possibly off the main thread) when the area
	 * is ready, or exceptionally on failure or timeout; callers continue either way.
	 */
	public CompletableFuture<Void> generate(World world, int x, int z, DoubleConsumer progress) {
		int radius = Math.max(0, options.radius());
		if (radius == 0) {
			progress.accept(1D);
			return CompletableFuture.completedFuture(null);
		}
		ChunkyBridge bridge = chunky();
		CompletableFuture<Void> future = bridge != null
			? bridge.generate(world, x, z, radius, progress)
			: loadDirectly(world, x, z, radius, progress);
		return future.orTimeout(Math.max(10, options.timeoutSeconds()), java.util.concurrent.TimeUnit.SECONDS)
			.whenComplete((ignored, error) -> {
				if (error != null && bridge != null) {
					Bukkit.getScheduler().runTask(plugin, () -> bridge.cancel(world));
				}
			});
	}

	/** Generate a square of {@code radius} blocks around x,z (no progress), with its own timeout. */
	public CompletableFuture<Void> generateArea(World world, int x, int z, int radius, int timeoutSeconds) {
		ChunkyBridge bridge = chunky();
		DoubleConsumer ignore = value -> { };
		CompletableFuture<Void> future = bridge != null
			? bridge.generate(world, x, z, radius, ignore)
			: loadDirectly(world, x, z, radius, ignore);
		return future.orTimeout(Math.max(30, timeoutSeconds), java.util.concurrent.TimeUnit.SECONDS)
			.whenComplete((ignored, error) -> {
				if (error != null && bridge != null) {
					Bukkit.getScheduler().runTask(plugin, () -> bridge.cancel(world));
				}
			});
	}

	/** Stop anything still generating in this world (a round cancelled mid-preparation). */
	public void cancel(World world) {
		if (chunky != null) {
			chunky.cancel(world);
		}
	}

	private CompletableFuture<Void> loadDirectly(World world, int x, int z, int radius, DoubleConsumer progress) {
		int minX = (x - radius) >> 4;
		int maxX = (x + radius) >> 4;
		int minZ = (z - radius) >> 4;
		int maxZ = (z + radius) >> 4;
		int width = maxX - minX + 1;
		int total = width * (maxZ - minZ + 1);
		AtomicInteger next = new AtomicInteger();
		AtomicInteger done = new AtomicInteger();
		CompletableFuture<Void> result = new CompletableFuture<>();

		Runnable[] pump = new Runnable[1];
		pump[0] = () -> {
			int index = next.getAndIncrement();
			if (index >= total || result.isDone()) {
				return;
			}
			int chunkX = minX + index % width;
			int chunkZ = minZ + index / width;
			world.getChunkAtAsync(chunkX, chunkZ, true).whenComplete((chunk, error) -> {
				int finished = done.incrementAndGet();
				progress.accept((double) finished / total);
				if (finished >= total) {
					result.complete(null);
				} else {
					pump[0].run();
				}
			});
		};
		Bukkit.getScheduler().runTask(plugin, () -> {
			for (int i = 0; i < Math.min(FALLBACK_IN_FLIGHT, total); i++) {
				pump[0].run();
			}
		});
		return result;
	}
}
